# Bakes Bebas Neue (SIL OFL 1.1, see tools/fonts/OFL.txt) into an 8-bit alpha atlas for the game:
# two weights (regular, and a heavier faux-bold made by stroking), ASCII 32..126.
import sys
from PIL import Image, ImageDraw, ImageFont
TTF = sys.argv[1]; OUT = sys.argv[2]
PX = 64
W, H = 1024, 512
font = ImageFont.truetype(TTF, PX)
atlas = Image.new('L', (W, H), 0)
d = ImageDraw.Draw(atlas)
glyphs = [[], []]
x, y, rowh = 2, 2, 0
asc, desc = font.getmetrics()
capb = font.getbbox('H', anchor='ls')
caph = -capb[1]
for wgt in range(2):
    stroke = 0 if wgt == 0 else 2
    for ch in range(32, 127):
        c = chr(ch)
        bb = font.getbbox(c, anchor='ls', stroke_width=stroke)      # relative to the baseline origin
        gw, gh = bb[2] - bb[0] + 2, bb[3] - bb[1] + 2
        adv = font.getlength(c) + stroke * 1.2
        if c == ' ':
            glyphs[wgt].append((0, 0, 0, 0, 0, 0, adv)); continue
        if x + gw + 2 > W: x = 2; y += rowh + 3; rowh = 0
        d.text((x + 1 - bb[0], y + 1 - bb[1]), c, font=font, fill=255, anchor='ls', stroke_width=stroke, stroke_fill=255)
        glyphs[wgt].append((x, y, x + gw, y + gh, bb[0] - 1, bb[1] - 1, adv))
        x += gw + 3; rowh = max(rowh, gh)
assert y + rowh < H, "atlas too small"
data = atlas.tobytes()
with open(OUT, 'w') as f:
    f.write('/* Bebas Neue by Dharma Type, SIL Open Font License 1.1 (tools/fonts/OFL.txt). Generated by tools/gen_font.py. */\n')
    f.write('#include "font_bebas.h"\n\n')
    f.write('const float FONT_CAP_H = %.3ff;\n' % caph)
    f.write('const FontGlyph FONT_GLYPH[2][95] = {\n')
    for wgt in range(2):
        f.write('  {\n')
        for g in glyphs[wgt]:
            f.write('    { %d, %d, %d, %d, %d, %d, %.2ff },\n' % g)
        f.write('  },\n')
    f.write('};\n\n')
    f.write('const unsigned char FONT_TEX[%d * %d] __attribute__((aligned(32))) = {\n' % (W, H))
    for i in range(0, len(data), 32):
        f.write(','.join(str(b) for b in data[i:i+32]) + ',\n')
    f.write('};\n')
atlas.save(OUT.replace('.c', '_preview.png'))
print('cap height', caph, 'last row y', y + rowh)
